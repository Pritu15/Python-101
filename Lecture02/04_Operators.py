# Arithmatic Operators

print(5+7)
print(6-5)
print(6*5)
print(6/5)
print(6//5)
print(5**2)
print(5%2)

# Relational Operator

print(4>5)
print(5<4)
print(4>=5)
print(5<=4)
print(4==4)
print(4!=5)

# Logical operator

print(1 and 0)
print(1 or 0)
print(not 1)

print(2 & 3)
print(2 | 3)
print(2 ^ 3)
print(~3)
